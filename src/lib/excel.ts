import * as XLSX from "xlsx";

function sanitizeCellValue(val: unknown): unknown {
  if (typeof val !== "string") return val;
  const trimmed = val.trim();
  if (/^[=+\-@\t\r]/.test(trimmed)) {
    return "'" + val;
  }
  return val;
}

/**
 * Adds BM Electronic copyright header (rows 1-2) and footer (last rows)
 * to every exported worksheet.
 */
export function addCopyrightHeader(
  worksheet: XLSX.WorkSheet,
  totalColumns: number,
  _sheetTitle: string
): void {
  const now = new Date();
  const dateStr = now.toLocaleString("en-NP", {
    year: "numeric",
    month: "short",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });

  // Determine last column letter
  const lastColLetter = XLSX.utils.encode_col(totalColumns - 1);

  // --- Shift all existing data down by 2 rows ---
  const range = XLSX.utils.decode_range(worksheet["!ref"] || "A1");
  // Walk from bottom-up to avoid overwriting
  for (let r = range.e.r; r >= range.s.r; r--) {
    for (let c = range.s.c; c <= range.e.c; c++) {
      const oldAddr = XLSX.utils.encode_cell({ r, c });
      const newAddr = XLSX.utils.encode_cell({ r: r + 2, c });
      if (worksheet[oldAddr]) {
        worksheet[newAddr] = worksheet[oldAddr];
        delete worksheet[oldAddr];
      }
    }
  }

  // Update the range
  range.s.r = 0;
  range.e.r += 2;
  worksheet["!ref"] = XLSX.utils.encode_range(range);

  // --- Insert copyright header at row 1 (index 0) ---
  const headerText =
    "BM Electronic \u2014 BM Store | \u00a9 2026 All Rights Reserved | Birendranagar, Surkhet, Nepal | Confidential \u2014 Internal Use Only";
  worksheet["A1"] = { t: "s", v: headerText };

  // Merge row 1 across all columns
  if (!worksheet["!merges"]) worksheet["!merges"] = [];
  worksheet["!merges"].push({
    s: { r: 0, c: 0 },
    e: { r: 0, c: totalColumns - 1 },
  });

  // Row 2 = spacer (already empty after shift)

  // --- Insert copyright footer after last data row ---
  const lastDataRow = range.e.r; // already updated
  const footerRow = lastDataRow + 2; // skip one spacer row

  const footerText = `Generated by BM Store v1.0.0 | \u00a9 2026 BM Electronic | Exported on: ${dateStr} | Confidential`;
  worksheet[XLSX.utils.encode_cell({ r: footerRow, c: 0 })] = {
    t: "s",
    v: footerText,
  };

  // Merge footer row across all columns
  worksheet["!merges"].push({
    s: { r: footerRow, c: 0 },
    e: { r: footerRow, c: totalColumns - 1 },
  });

  // Update range to include footer
  range.e.r = footerRow;
  worksheet["!ref"] = XLSX.utils.encode_range(range);

  // --- Set row heights ---
  if (!worksheet["!rows"]) worksheet["!rows"] = [];
  worksheet["!rows"][0] = { hpt: 22 }; // header row
  worksheet["!rows"][1] = { hpt: 6 }; // spacer
  worksheet["!rows"][lastDataRow + 1] = { hpt: 6 }; // spacer before footer
  worksheet["!rows"][footerRow] = { hpt: 18 }; // footer row
}

export function exportRows(rows: Record<string, unknown>[], sheetName: string, fileName: string) {
  const sanitized = rows.map((row) => {
    const clean: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(row)) {
      clean[k] = sanitizeCellValue(v);
    }
    return clean;
  });
  const ws = XLSX.utils.json_to_sheet(sanitized);
  const totalColumns = rows.length > 0 ? Object.keys(rows[0]).length : 1;
  addCopyrightHeader(ws, totalColumns, sheetName);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, sheetName);
  XLSX.writeFile(wb, fileName);
}
